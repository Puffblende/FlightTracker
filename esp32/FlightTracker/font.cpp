// ---------------------------------------------------------------------------
// Pixel distribution helpers — port of Python _split_ranges / _scaled_dim
// ---------------------------------------------------------------------------

static int scaledDim(int n, float scale) {
    int v = (int)roundf((float)n * scale);
    return v < 1 ? 1 : v;
}

static void splitRanges(int n_in, int n_out, int* starts, int* ends) {
    for (int i = 0; i < n_in; i++) {
        starts[i] = (i * n_out) / n_in;
        ends[i]   = ((i + 1) * n_out) / n_in;
    }
}

// ---------------------------------------------------------------------------
// Core character renderer
// ---------------------------------------------------------------------------

static void drawCharInternal(int x, int y, char c,
                             uint8_t r, uint8_t g, uint8_t b,
                             int clipX,
                             const int rowStarts[], const int rowEnds[],
                             const int colStarts[], const int colEnds[]) {
    uint8_t idx = (uint8_t)c;
    if (idx >= 128) idx = (uint8_t)' ';
    const uint8_t* rows = FONT_5X7[idx];

    for (int ry = 0; ry < FONT_CHAR_H; ry++) {
        uint8_t bits = rows[ry];
        if (!bits) continue;
        int rStart = rowStarts[ry], rEnd = rowEnds[ry];
        for (int bx = 0; bx < FONT_CHAR_W; bx++) {
            if (!(bits & (1 << (FONT_CHAR_W - 1 - bx)))) continue;
            int cStart = colStarts[bx], cEnd = colEnds[bx];
            for (int dy = rStart; dy < rEnd; dy++) {
                int py = y + dy;
                if (py < 0 || py >= TOTAL_HEIGHT) continue;
                for (int dx = cStart; dx < cEnd; dx++) {
                    int px = x + dx;
                    if (px >= 0 && px < TOTAL_WIDTH && px < clipX)
                        displaySetPixel(px, py, r, g, b);
                }
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

int fontCharAdvance(float scale) {
    return scaledDim(FONT_CHAR_W, scale) +
           (int)roundf((float)FONT_CHAR_SPACING * scale);
}

int fontTextWidth(const char* text, float scale) {
    if (!text || !text[0]) return 0;
    int cw  = scaledDim(FONT_CHAR_W, scale);
    int sp  = (int)roundf((float)FONT_CHAR_SPACING * scale);
    int len = (int)strlen(text);
    return len * (cw + sp) - sp;
}

int fontDrawText(int x, int y, const char* text,
                 uint8_t r, uint8_t g, uint8_t b,
                 float scale, int maxWidth) {
    if (!text) return x;

    int charWOut = scaledDim(FONT_CHAR_W, scale);
    int charHOut = scaledDim(FONT_CHAR_H, scale);
    int spOut    = (int)roundf((float)FONT_CHAR_SPACING * scale);
    if (spOut < 0) spOut = 0;
    int advance  = charWOut + spOut;

    int rowStarts[FONT_CHAR_H], rowEnds[FONT_CHAR_H];
    int colStarts[FONT_CHAR_W], colEnds[FONT_CHAR_W];
    splitRanges(FONT_CHAR_H, charHOut, rowStarts, rowEnds);
    splitRanges(FONT_CHAR_W, charWOut, colStarts, colEnds);

    int clipX = (maxWidth > 0) ? (x + maxWidth) : TOTAL_WIDTH;
    int cx = x;
    for (int i = 0; text[i] != '\0'; i++) {
        if (cx >= clipX) break;
        drawCharInternal(cx, y, text[i], r, g, b, clipX,
                         rowStarts, rowEnds, colStarts, colEnds);
        cx += advance;
    }
    return cx;
}
